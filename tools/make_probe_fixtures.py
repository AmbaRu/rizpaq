#!/usr/bin/env python3

























from __future__ import annotations

import sys
from pathlib import Path


HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
OUT = ROOT / "tests" / "probe_out"

INFO_NAME = "01_info_comment.txt"
LIST_ALL_NAME = "07_list_all_terse_csv_tab_csvhf_utf.txt"
LIST_LAST_NAME = "08_list_last_terse_csv_tab_csvhf_utf.txt"

DT = "2026-06-12 20:25:10"

DIR_PATH = "d:/1000/Распечатано/"
DIR_SIZE = "39.551.238"

XLSX_PATH = "d:/1000/ошибки.xlsx"
XLSX_SIZE = "9.396"

JSON_PATH = "d:/1000/04ee2e9d-eb6e-470c-bfcc-4fe34cde01de.json"
JSON_SIZE = "4.371"

                                                     
                                
GENERIC_FILE_COUNT = 134


def wrap_csvhf(line: str) -> str:
    pass
    return "#" + line + "#"


def build_rows() -> list:
    pass



    rows = []

            
    rows.append(("D", DIR_SIZE, "dir", "#", DIR_PATH))

                                
    rows.append(("A", XLSX_SIZE, "0.00", "+", XLSX_PATH))
    rows.append(("A", JSON_SIZE, "0.00", "+", JSON_PATH))

                    
    for i in range(1, GENERIC_FILE_COUNT + 1):
        path = f"d:/1000/file_{i:04d}.txt"
        size = str(1000 + i)
        rows.append(("A", size, "0.00", "+", path))

    return rows


def make_all_line(row: tuple) -> str:
    pass






    attr, size, ratio, flag, path = row
    fields = [DT, attr, size, ratio, "1", flag, path]
    return wrap_csvhf("\t".join(fields))


def make_last_line(row: tuple) -> str:
    pass






    attr, size, ratio, flag, path = row
    fields = [DT, attr, size, ratio, flag, path]
    return wrap_csvhf("\t".join(fields))


def write_list_file(path: Path, rows: list, line_maker) -> None:
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        for row in rows:
            f.write(line_maker(row) + "\n")


def write_info_file(path: Path) -> None:
    lines = [
        "# probe fixture generated by tools/make_probe_fixtures.py",
        "zpaqfranz v64.7g-JIT,SFTP,RES-L,HW BLK3,SHA1/2,4,SFX64 55.1,(2026-03-24)",
        "",
        "1 versions, 137 files, 42.365.169 bytes",
        "V1 2026-06-12 20:25:10 +137 -0 -> 42.365.169 probe",
        "",
    ]

    with open(path, "w", encoding="utf-8", newline="\n") as f:
        for line in lines:
            f.write(line + "\n")


def self_check() -> None:
    pass
    if str(ROOT) not in sys.path:
        sys.path.insert(0, str(ROOT))

    from core.parser import parse_csv_list, parse_info

    all_text = (OUT / LIST_ALL_NAME).read_text(encoding="utf-8")
    last_text = (OUT / LIST_LAST_NAME).read_text(encoding="utf-8")
    info_text = (OUT / INFO_NAME).read_text(encoding="utf-8")

    all_entries = parse_csv_list(all_text)
    last_entries = parse_csv_list(last_text)

                                
    assert len(all_entries) == 137
    assert sum(1 for e in all_entries if e.is_dir) == 1
    assert sum(1 for e in all_entries if not e.is_dir) == 136

                                
    assert all(e.path.startswith("d:/1000") for e in all_entries)
    assert all(e.version == 1 for e in all_entries)

            
    dirs = [e for e in all_entries if e.is_dir]
    assert len(dirs) == 1
    assert dirs[0].path == "d:/1000/Распечатано"
    assert dirs[0].size == 39551238
    assert dirs[0].version == 1

                     
    xlsx = [e for e in all_entries if e.path.endswith("ошибки.xlsx")]
    assert len(xlsx) == 1
    assert xlsx[0].size == 9396

                     
    js = [e for e in all_entries if e.path == JSON_PATH]
    assert len(js) == 1
    assert js[0].size == 4371

                                                 
    assert len(last_entries) == len(all_entries)
    assert all(e.version is None for e in last_entries)

                                   
    last_dirs = [e for e in last_entries if e.is_dir]
    assert len(last_dirs) == 1
    assert last_dirs[0].path == "d:/1000/Распечатано"

           
    summary, versions = parse_info(info_text)

    assert summary is not None
    assert summary.versions == 1
    assert summary.files == 137
    assert summary.size == 42365169

    assert len(versions) == 1

    v = versions[0]
    assert v.number == 1
    assert v.date == "2026-06-12"
    assert v.time == "20:25:10"
    assert v.added == 137
    assert v.removed == 0
    assert v.bytes_added == 42365169


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)

    rows = build_rows()

    write_list_file(OUT / LIST_ALL_NAME, rows, make_all_line)
    write_list_file(OUT / LIST_LAST_NAME, rows, make_last_line)
    write_info_file(OUT / INFO_NAME)

    self_check()

    print("Probe fixtures created:")
    print(f"  {OUT / INFO_NAME}")
    print(f"  {OUT / LIST_ALL_NAME}")
    print(f"  {OUT / LIST_LAST_NAME}")
    print("Parser self-check: OK")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
